// Од тастатура се внесуваат димензиите на една матрица (m,n <= 100), а потоа и елементите од матрицата. Да се трансформира матрицата така што средниот елемент во секоја редица ќе се замени со разликата (по апсолутна вредност) на сумата на елементите во првата половина од редицата и сумата на елементите во втората половина на редицата. Ако матрицата има парен број колони, се менува вредноста на средните два елемента. Средниот/те елемент/и влегува/ат во сумите (при непарен број на колони, средниот елемент влегува во двете суми!). Да се испечати на екран променетата матрица.

// Пример.

// Влез:

// m = 4

// n = 4

// 1 3 -5 4

// 2 10 2 10

// 7 2 3 5

// 3 2 10 3

// Излез:

// 1 5 5 4

// 2 0 0 10

// 7 1 1 5

// 3 8 8 3


#include <iostream>
#include <cstring>
using namespace std;
int main() {
    int n,m;
    cin>>n>>m;
    int mat[100][100];
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cin>>mat[i][j];
        }
    }
    if (m % 2 == 0) {
        for (int i = 0; i < n; i++) {
            int suma1 = 0;
            int suma2 = 0;
            for (int j = 0; j < m / 2; j++) {
                suma1 = suma1 + mat[i][j];

            }
            for (int j = m / 2; j < m; j++) {
                suma2 = suma2 + mat[i][j];

            }
            int rez = abs(suma1 - suma2);
                mat[i][m / 2 - 1] = rez;
            mat[i][m / 2] = rez;
        }

    }else{
        for (int i = 0; i < n; i++) {
            int suma1 = 0;
            int suma2 = 0;
            for (int j = 0; j <= m / 2; j++) {
                suma1 = suma1 + mat[i][j];
            }
            for (int j = m / 2; j < m; j++) {
                suma2 = suma2 + mat[i][j];

            }
            int rez = abs(suma1 - suma2);
            mat[i][m / 2] = rez;
        }
    }
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cout<<mat[i][j]<<" ";
        }
        cout<<endl;
    }
    return 0;
}
